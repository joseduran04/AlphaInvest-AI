CREATE TABLE IF NOT EXISTS audit.registros_auditoria
(
    id BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        CONSTRAINT pk_registros_auditoria
        PRIMARY KEY,

    usuario_id UUID NULL,

    esquema_entidad VARCHAR(63) NOT NULL,

    nombre_entidad VARCHAR(100) NOT NULL,

    registro_id VARCHAR(150) NULL,

    accion VARCHAR(30) NOT NULL,

    valores_anteriores JSONB NULL,

    valores_nuevos JSONB NULL,

    campos_modificados JSONB NULL,

    direccion_ip INET NULL,

    agente_usuario TEXT NULL,

    origen VARCHAR(50) NOT NULL
        DEFAULT 'APLICACION',

    identificador_solicitud VARCHAR(150) NULL,

    fecha_evento TIMESTAMPTZ NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_registros_auditoria_usuario
        FOREIGN KEY (usuario_id)
        REFERENCES app_auth.usuarios (id)
        ON UPDATE CASCADE
        ON DELETE SET NULL,

    CONSTRAINT ck_registros_auditoria_esquema
        CHECK
        (
            LENGTH(TRIM(esquema_entidad)) > 0
        ),

    CONSTRAINT ck_registros_auditoria_entidad
        CHECK
        (
            LENGTH(TRIM(nombre_entidad)) > 0
        ),

    CONSTRAINT ck_registros_auditoria_registro
        CHECK
        (
            registro_id IS NULL
            OR LENGTH(TRIM(registro_id)) > 0
        ),

    CONSTRAINT ck_registros_auditoria_accion
        CHECK
        (
            accion IN
            (
                'INSERT',
                'UPDATE',
                'DELETE',
                'LOGIN',
                'LOGOUT',
                'LECTURA',
                'EXPORTACION',
                'EJECUCION',
                'OTRA'
            )
        ),

    CONSTRAINT ck_registros_auditoria_valores_anteriores
        CHECK
        (
            valores_anteriores IS NULL
            OR jsonb_typeof(valores_anteriores) = 'object'
        ),

    CONSTRAINT ck_registros_auditoria_valores_nuevos
        CHECK
        (
            valores_nuevos IS NULL
            OR jsonb_typeof(valores_nuevos) = 'object'
        ),

    CONSTRAINT ck_registros_auditoria_campos_modificados
        CHECK
        (
            campos_modificados IS NULL
            OR jsonb_typeof(campos_modificados) = 'array'
        ),

    CONSTRAINT ck_registros_auditoria_origen
        CHECK
        (
            origen IN
            (
                'APLICACION',
                'BASE_DATOS',
                'API',
                'TRABAJO_PROGRAMADO',
                'ADMINISTRACION',
                'SISTEMA'
            )
        ),

    CONSTRAINT ck_registros_auditoria_identificador_solicitud
        CHECK
        (
            identificador_solicitud IS NULL
            OR LENGTH(TRIM(identificador_solicitud)) > 0
        ),

    CONSTRAINT ck_registros_auditoria_contenido
        CHECK
        (
            accion NOT IN ('INSERT', 'UPDATE', 'DELETE')
            OR registro_id IS NOT NULL
        )
);

COMMENT ON TABLE audit.registros_auditoria IS
'Historial de acciones relevantes realizadas sobre entidades y recursos de AlphaInvest AI.';

COMMENT ON COLUMN audit.registros_auditoria.usuario_id IS
'Usuario responsable de la acción, cuando pueda identificarse.';

COMMENT ON COLUMN audit.registros_auditoria.esquema_entidad IS
'Esquema PostgreSQL de la entidad afectada.';

COMMENT ON COLUMN audit.registros_auditoria.nombre_entidad IS
'Nombre de la tabla, recurso o entidad afectada.';

COMMENT ON COLUMN audit.registros_auditoria.registro_id IS
'Identificador textual del registro afectado.';

COMMENT ON COLUMN audit.registros_auditoria.accion IS
'Operación realizada sobre la entidad o recurso.';

COMMENT ON COLUMN audit.registros_auditoria.valores_anteriores IS
'Estado del registro antes de la modificación.';

COMMENT ON COLUMN audit.registros_auditoria.valores_nuevos IS
'Estado del registro después de la modificación.';

COMMENT ON COLUMN audit.registros_auditoria.campos_modificados IS
'Lista de campos modificados durante una actualización.';

COMMENT ON COLUMN audit.registros_auditoria.identificador_solicitud IS
'Identificador de correlación de la petición que originó el evento.';


/*
============================================================
 2. TABLA: audit.eventos_seguridad
============================================================
*/

CREATE TABLE IF NOT EXISTS audit.eventos_seguridad
(
    id UUID
        CONSTRAINT pk_eventos_seguridad
        PRIMARY KEY
        DEFAULT gen_random_uuid(),

    usuario_id UUID NULL,

    correo_intentado CITEXT NULL,

    tipo_evento VARCHAR(50) NOT NULL,

    severidad VARCHAR(20) NOT NULL
        DEFAULT 'BAJA',

    resultado VARCHAR(20) NOT NULL,

    direccion_ip INET NULL,

    agente_usuario TEXT NULL,

    recurso VARCHAR(200) NULL,

    descripcion TEXT NOT NULL,

    metadatos JSONB NULL,

    fecha_evento TIMESTAMPTZ NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    revisado BOOLEAN NOT NULL
        DEFAULT FALSE,

    revisado_por UUID NULL,

    fecha_revision TIMESTAMPTZ NULL,

    observaciones_revision TEXT NULL,

    CONSTRAINT fk_eventos_seguridad_usuario
        FOREIGN KEY (usuario_id)
        REFERENCES app_auth.usuarios (id)
        ON UPDATE CASCADE
        ON DELETE SET NULL,

    CONSTRAINT fk_eventos_seguridad_revisor
        FOREIGN KEY (revisado_por)
        REFERENCES app_auth.usuarios (id)
        ON UPDATE CASCADE
        ON DELETE SET NULL,

    CONSTRAINT ck_eventos_seguridad_correo
        CHECK
        (
            correo_intentado IS NULL
            OR LENGTH(TRIM(correo_intentado::TEXT)) > 0
        ),

    CONSTRAINT ck_eventos_seguridad_tipo
        CHECK
        (
            tipo_evento IN
            (
                'LOGIN_EXITOSO',
                'LOGIN_FALLIDO',
                'USUARIO_BLOQUEADO',
                'TOKEN_INVALIDO',
                'TOKEN_EXPIRADO',
                'ACCESO_DENEGADO',
                'PERMISO_INSUFICIENTE',
                'CAMBIO_PASSWORD',
                'RECUPERACION_PASSWORD',
                'SESION_REVOCADA',
                'ACTIVIDAD_SOSPECHOSA',
                'OTRO'
            )
        ),

    CONSTRAINT ck_eventos_seguridad_severidad
        CHECK
        (
            severidad IN
            (
                'BAJA',
                'MEDIA',
                'ALTA',
                'CRITICA'
            )
        ),

    CONSTRAINT ck_eventos_seguridad_resultado
        CHECK
        (
            resultado IN
            (
                'EXITOSO',
                'FALLIDO',
                'BLOQUEADO',
                'DENEGADO',
                'INFORMATIVO'
            )
        ),

    CONSTRAINT ck_eventos_seguridad_recurso
        CHECK
        (
            recurso IS NULL
            OR LENGTH(TRIM(recurso)) > 0
        ),

    CONSTRAINT ck_eventos_seguridad_descripcion
        CHECK
        (
            LENGTH(TRIM(descripcion)) > 0
        ),

    CONSTRAINT ck_eventos_seguridad_metadatos
        CHECK
        (
            metadatos IS NULL
            OR jsonb_typeof(metadatos) = 'object'
        ),

    CONSTRAINT ck_eventos_seguridad_revision
        CHECK
        (
            (
                revisado = FALSE
                AND fecha_revision IS NULL
                AND revisado_por IS NULL
            )
            OR
            (
                revisado = TRUE
                AND fecha_revision IS NOT NULL
                AND revisado_por IS NOT NULL
            )
        ),

    CONSTRAINT ck_eventos_seguridad_fecha_revision
        CHECK
        (
            fecha_revision IS NULL
            OR fecha_revision >= fecha_evento
        ),

    CONSTRAINT ck_eventos_seguridad_observaciones
        CHECK
        (
            observaciones_revision IS NULL
            OR LENGTH(TRIM(observaciones_revision)) > 0
        )
);

COMMENT ON TABLE audit.eventos_seguridad IS
'Eventos relacionados con autenticación, autorización y actividad potencialmente sospechosa.';

COMMENT ON COLUMN audit.eventos_seguridad.correo_intentado IS
'Correo proporcionado en un intento de acceso, incluso si no corresponde a un usuario registrado.';

COMMENT ON COLUMN audit.eventos_seguridad.severidad IS
'Gravedad operativa y de seguridad asignada al evento.';

COMMENT ON COLUMN audit.eventos_seguridad.resultado IS
'Resultado de la operación relacionada con seguridad.';

COMMENT ON COLUMN audit.eventos_seguridad.revisado IS
'Indica si el evento fue revisado por un usuario autorizado.';


