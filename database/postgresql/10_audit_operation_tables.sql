 7. TABLA: operation.control_procesos
============================================================
*/

CREATE TABLE IF NOT EXISTS operation.control_procesos
(
    id UUID
        CONSTRAINT pk_control_procesos
        PRIMARY KEY
        DEFAULT gen_random_uuid(),

    tipo_proceso VARCHAR(50) NOT NULL,

    entidad_tipo VARCHAR(50) NULL,

    entidad_id VARCHAR(150) NULL,

    clave_bloqueo VARCHAR(200) NOT NULL,

    estado VARCHAR(30) NOT NULL
        DEFAULT 'ADQUIRIDO',

    propietario VARCHAR(150) NOT NULL,

    identificador_proceso VARCHAR(150) NOT NULL,

    fecha_adquisicion TIMESTAMPTZ NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    fecha_expiracion TIMESTAMPTZ NOT NULL,

    fecha_liberacion TIMESTAMPTZ NULL,

    latido_actualizacion TIMESTAMPTZ NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    metadatos JSONB NULL,

    CONSTRAINT uq_control_procesos_clave
        UNIQUE (clave_bloqueo),

    CONSTRAINT uq_control_procesos_identificador
        UNIQUE (identificador_proceso),

    CONSTRAINT ck_control_procesos_tipo
        CHECK
        (
            tipo_proceso IN
            (
                'SIMULACION',
                'ANALISIS_IA',
                'CARGA_MERCADO',
                'ENVIO_NOTIFICACION',
                'TRABAJO_PROGRAMADO',
                'MANTENIMIENTO',
                'OTRO'
            )
        ),

    CONSTRAINT ck_control_procesos_entidad
        CHECK
        (
            (
                entidad_tipo IS NULL
                AND entidad_id IS NULL
            )
            OR
            (
                entidad_tipo IS NOT NULL
                AND entidad_id IS NOT NULL
                AND LENGTH(TRIM(entidad_tipo)) > 0
                AND LENGTH(TRIM(entidad_id)) > 0
            )
        ),

    CONSTRAINT ck_control_procesos_clave
        CHECK
        (
            LENGTH(TRIM(clave_bloqueo)) > 0
        ),

    CONSTRAINT ck_control_procesos_estado
        CHECK
        (
            estado IN
            (
                'ADQUIRIDO',
                'LIBERADO',
                'EXPIRADO',
                'CANCELADO'
            )
        ),

    CONSTRAINT ck_control_procesos_propietario
        CHECK
        (
            LENGTH(TRIM(propietario)) > 0
        ),

    CONSTRAINT ck_control_procesos_identificador
        CHECK
        (
            LENGTH(TRIM(identificador_proceso)) > 0
        ),

    CONSTRAINT ck_control_procesos_expiracion
        CHECK
        (
            fecha_expiracion > fecha_adquisicion
        ),

    CONSTRAINT ck_control_procesos_liberacion
        CHECK
        (
            fecha_liberacion IS NULL
            OR fecha_liberacion >= fecha_adquisicion
        ),

    CONSTRAINT ck_control_procesos_latido
        CHECK
        (
            latido_actualizacion >= fecha_adquisicion
        ),

    CONSTRAINT ck_control_procesos_estado_liberado
        CHECK
        (
            estado <> 'LIBERADO'
            OR fecha_liberacion IS NOT NULL
        ),

    CONSTRAINT ck_control_procesos_estado_adquirido
        CHECK
        (
            estado <> 'ADQUIRIDO'
            OR fecha_liberacion IS NULL
        ),

    CONSTRAINT ck_control_procesos_metadatos
        CHECK
        (
            metadatos IS NULL
            OR jsonb_typeof(metadatos) = 'object'
        )
);

COMMENT ON TABLE operation.control_procesos IS
'Mecanismo de control y bloqueo lógico para evitar procesamientos simultáneos incompatibles.';

COMMENT ON COLUMN operation.control_procesos.clave_bloqueo IS
'Clave única que representa el recurso o proceso bloqueado.';

COMMENT ON COLUMN operation.control_procesos.propietario IS
'Instancia, servicio o trabajador que adquirió el bloqueo.';

COMMENT ON COLUMN operation.control_procesos.fecha_expiracion IS
'Fecha límite después de la cual el bloqueo puede considerarse abandonado.';

COMMENT ON COLUMN operation.control_procesos.latido_actualizacion IS
'Última señal de actividad enviada por el proceso propietario.';

COMMENT ON COLUMN operation.control_procesos.metadatos IS
'Información adicional necesaria para supervisar el proceso.';


