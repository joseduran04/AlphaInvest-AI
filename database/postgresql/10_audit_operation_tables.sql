 3. TABLA: audit.errores_aplicacion
============================================================
*/

CREATE TABLE IF NOT EXISTS audit.errores_aplicacion
(
    id UUID
        CONSTRAINT pk_errores_aplicacion
        PRIMARY KEY
        DEFAULT gen_random_uuid(),

    usuario_id UUID NULL,

    servicio VARCHAR(100) NOT NULL,

    componente VARCHAR(150) NULL,

    entorno VARCHAR(30) NOT NULL,

    nivel VARCHAR(20) NOT NULL,

    codigo_error VARCHAR(100) NULL,

    tipo_excepcion VARCHAR(200) NULL,

    mensaje TEXT NOT NULL,

    detalle TEXT NULL,

    traza TEXT NULL,

    metodo_http VARCHAR(10) NULL,

    ruta_solicitud VARCHAR(500) NULL,

    codigo_http INTEGER NULL,

    identificador_solicitud VARCHAR(150) NULL,

    identificador_proceso VARCHAR(150) NULL,

    direccion_ip INET NULL,

    datos_contexto JSONB NULL,

    fecha_error TIMESTAMPTZ NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    resuelto BOOLEAN NOT NULL
        DEFAULT FALSE,

    fecha_resolucion TIMESTAMPTZ NULL,

    resuelto_por UUID NULL,

    notas_resolucion TEXT NULL,

    CONSTRAINT fk_errores_aplicacion_usuario
        FOREIGN KEY (usuario_id)
        REFERENCES app_auth.usuarios (id)
        ON UPDATE CASCADE
        ON DELETE SET NULL,

    CONSTRAINT fk_errores_aplicacion_resuelto_por
        FOREIGN KEY (resuelto_por)
        REFERENCES app_auth.usuarios (id)
        ON UPDATE CASCADE
        ON DELETE SET NULL,

    CONSTRAINT ck_errores_aplicacion_servicio
        CHECK
        (
            LENGTH(TRIM(servicio)) > 0
        ),

    CONSTRAINT ck_errores_aplicacion_componente
        CHECK
        (
            componente IS NULL
            OR LENGTH(TRIM(componente)) > 0
        ),

    CONSTRAINT ck_errores_aplicacion_entorno
        CHECK
        (
            entorno IN
            (
                'LOCAL',
                'DESARROLLO',
                'PRUEBAS',
                'STAGING',
                'PRODUCCION'
            )
        ),

    CONSTRAINT ck_errores_aplicacion_nivel
        CHECK
        (
            nivel IN
            (
                'INFO',
                'WARNING',
                'ERROR',
                'CRITICAL'
            )
        ),

    CONSTRAINT ck_errores_aplicacion_codigo
        CHECK
        (
            codigo_error IS NULL
            OR LENGTH(TRIM(codigo_error)) > 0
        ),

    CONSTRAINT ck_errores_aplicacion_tipo_excepcion
        CHECK
        (
            tipo_excepcion IS NULL
            OR LENGTH(TRIM(tipo_excepcion)) > 0
        ),

    CONSTRAINT ck_errores_aplicacion_mensaje
        CHECK
        (
            LENGTH(TRIM(mensaje)) > 0
        ),

    CONSTRAINT ck_errores_aplicacion_metodo_http
        CHECK
        (
            metodo_http IS NULL
            OR metodo_http IN
            (
                'GET',
                'POST',
                'PUT',
                'PATCH',
                'DELETE',
                'OPTIONS',
                'HEAD'
            )
        ),

    CONSTRAINT ck_errores_aplicacion_ruta
        CHECK
        (
            ruta_solicitud IS NULL
            OR LENGTH(TRIM(ruta_solicitud)) > 0
        ),

    CONSTRAINT ck_errores_aplicacion_codigo_http
        CHECK
        (
            codigo_http IS NULL
            OR codigo_http BETWEEN 100 AND 599
        ),

    CONSTRAINT ck_errores_aplicacion_identificador_solicitud
        CHECK
        (
            identificador_solicitud IS NULL
            OR LENGTH(TRIM(identificador_solicitud)) > 0
        ),

    CONSTRAINT ck_errores_aplicacion_identificador_proceso
        CHECK
        (
            identificador_proceso IS NULL
            OR LENGTH(TRIM(identificador_proceso)) > 0
        ),

    CONSTRAINT ck_errores_aplicacion_contexto
        CHECK
        (
            datos_contexto IS NULL
            OR jsonb_typeof(datos_contexto) = 'object'
        ),

    CONSTRAINT ck_errores_aplicacion_resolucion
        CHECK
        (
            (
                resuelto = FALSE
                AND fecha_resolucion IS NULL
                AND resuelto_por IS NULL
            )
            OR
            (
                resuelto = TRUE
                AND fecha_resolucion IS NOT NULL
                AND resuelto_por IS NOT NULL
            )
        ),

    CONSTRAINT ck_errores_aplicacion_fecha_resolucion
        CHECK
        (
            fecha_resolucion IS NULL
            OR fecha_resolucion >= fecha_error
        ),

    CONSTRAINT ck_errores_aplicacion_notas
        CHECK
        (
            notas_resolucion IS NULL
            OR LENGTH(TRIM(notas_resolucion)) > 0
        )
);

COMMENT ON TABLE audit.errores_aplicacion IS
'Registro centralizado de errores y excepciones ocurridos en los servicios de AlphaInvest AI.';

COMMENT ON COLUMN audit.errores_aplicacion.servicio IS
'Servicio que reportó el error, por ejemplo API, MOTOR_IA o MARKET_SERVICE.';

COMMENT ON COLUMN audit.errores_aplicacion.nivel IS
'Nivel de gravedad técnica del evento registrado.';

COMMENT ON COLUMN audit.errores_aplicacion.identificador_solicitud IS
'Identificador utilizado para correlacionar el error con una petición del usuario.';

COMMENT ON COLUMN audit.errores_aplicacion.datos_contexto IS
'Información técnica adicional necesaria para diagnosticar el error.';

COMMENT ON COLUMN audit.errores_aplicacion.resuelto IS
'Indica si el error fue investigado y marcado como resuelto.';


/*
============================================================
 4. TABLA: operation.notificaciones
============================================================
*/

CREATE TABLE IF NOT EXISTS operation.notificaciones
(
    id UUID
        CONSTRAINT pk_notificaciones
        PRIMARY KEY
        DEFAULT gen_random_uuid(),

    usuario_id UUID NOT NULL,

    tipo VARCHAR(40) NOT NULL,

    canal VARCHAR(20) NOT NULL,

    titulo VARCHAR(200) NOT NULL,

    mensaje TEXT NOT NULL,

    prioridad VARCHAR(20) NOT NULL
        DEFAULT 'NORMAL',

    estado VARCHAR(30) NOT NULL
        DEFAULT 'PENDIENTE',

    datos JSONB NULL,

    fecha_creacion TIMESTAMPTZ NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    fecha_programada TIMESTAMPTZ NULL,

    fecha_envio TIMESTAMPTZ NULL,

    fecha_lectura TIMESTAMPTZ NULL,

    intentos_envio INTEGER NOT NULL
        DEFAULT 0,

    ultimo_error TEXT NULL,

    referencia_tipo VARCHAR(50) NULL,

    referencia_id VARCHAR(150) NULL,

    CONSTRAINT fk_notificaciones_usuario
        FOREIGN KEY (usuario_id)
        REFERENCES app_auth.usuarios (id)
        ON UPDATE CASCADE
        ON DELETE CASCADE,

    CONSTRAINT ck_notificaciones_tipo
        CHECK
        (
            tipo IN
            (
                'SISTEMA',
                'SEGURIDAD',
                'ALERTA_PRECIO',
                'SIMULACION',
                'ANALISIS_IA',
                'RECOMENDACION',
                'PORTAFOLIO',
                'MANTENIMIENTO',
                'OTRA'
            )
        ),

    CONSTRAINT ck_notificaciones_canal
        CHECK
        (
            canal IN
            (
                'APLICACION',
                'CORREO',
                'PUSH'
            )
        ),

    CONSTRAINT ck_notificaciones_titulo
        CHECK
        (
            LENGTH(TRIM(titulo)) > 0
        ),

    CONSTRAINT ck_notificaciones_mensaje
        CHECK
        (
            LENGTH(TRIM(mensaje)) > 0
        ),

    CONSTRAINT ck_notificaciones_prioridad
        CHECK
        (
            prioridad IN
            (
                'BAJA',
                'NORMAL',
                'ALTA',
                'URGENTE'
            )
        ),

    CONSTRAINT ck_notificaciones_estado
        CHECK
        (
            estado IN
            (
                'PENDIENTE',
                'PROGRAMADA',
                'ENVIANDO',
                'ENVIADA',
                'FALLIDA',
                'CANCELADA'
            )
        ),

    CONSTRAINT ck_notificaciones_datos
        CHECK
        (
            datos IS NULL
            OR jsonb_typeof(datos) = 'object'
        ),

    CONSTRAINT ck_notificaciones_fecha_programada
        CHECK
        (
            fecha_programada IS NULL
            OR fecha_programada >= fecha_creacion
        ),

    CONSTRAINT ck_notificaciones_fecha_envio
        CHECK
        (
            fecha_envio IS NULL
            OR fecha_envio >= fecha_creacion
        ),

    CONSTRAINT ck_notificaciones_fecha_lectura
        CHECK
        (
            fecha_lectura IS NULL
            OR
            (
                fecha_envio IS NOT NULL
                AND fecha_lectura >= fecha_envio
            )
        ),

    CONSTRAINT ck_notificaciones_intentos
        CHECK
        (
            intentos_envio >= 0
        ),

    CONSTRAINT ck_notificaciones_estado_programada
        CHECK
        (
            estado <> 'PROGRAMADA'
            OR fecha_programada IS NOT NULL
        ),

    CONSTRAINT ck_notificaciones_estado_enviada
        CHECK
        (
            estado <> 'ENVIADA'
            OR fecha_envio IS NOT NULL
        ),

    CONSTRAINT ck_notificaciones_estado_fallida
        CHECK
        (
            estado <> 'FALLIDA'
            OR NULLIF(TRIM(ultimo_error), '') IS NOT NULL
        ),

    CONSTRAINT ck_notificaciones_referencia
        CHECK
        (
            (
                referencia_tipo IS NULL
                AND referencia_id IS NULL
            )
            OR
            (
                referencia_tipo IS NOT NULL
                AND referencia_id IS NOT NULL
                AND LENGTH(TRIM(referencia_tipo)) > 0
                AND LENGTH(TRIM(referencia_id)) > 0
            )
        )
);

COMMENT ON TABLE operation.notificaciones IS
'Notificaciones generadas para los usuarios de AlphaInvest AI.';

COMMENT ON COLUMN operation.notificaciones.canal IS
'Medio mediante el cual debe enviarse la notificación.';

COMMENT ON COLUMN operation.notificaciones.estado IS
'Estado operativo del proceso de envío.';

COMMENT ON COLUMN operation.notificaciones.datos IS
'Información estructurada utilizada por la interfaz o plantilla de notificación.';

COMMENT ON COLUMN operation.notificaciones.referencia_tipo IS
'Tipo de entidad relacionada, por ejemplo RECOMENDACION o SIMULACION.';

COMMENT ON COLUMN operation.notificaciones.referencia_id IS
'Identificador de la entidad relacionada con la notificación.';


/*
============================================================
 5. TABLA: operation.trabajos_programados
============================================================
*/

CREATE TABLE IF NOT EXISTS operation.trabajos_programados
(
    id UUID
        CONSTRAINT pk_trabajos_programados
        PRIMARY KEY
        DEFAULT gen_random_uuid(),

    codigo VARCHAR(100) NOT NULL,

    nombre VARCHAR(150) NOT NULL,

    descripcion TEXT NULL,

    tipo VARCHAR(40) NOT NULL,

    expresion_cron VARCHAR(100) NULL,

    intervalo_segundos INTEGER NULL,

    zona_horaria VARCHAR(80) NOT NULL
        DEFAULT 'UTC',

    parametros JSONB NULL,

    activo BOOLEAN NOT NULL
        DEFAULT TRUE,

    permite_concurrencia BOOLEAN NOT NULL
        DEFAULT FALSE,

    tiempo_maximo_segundos INTEGER NULL,

    maximo_reintentos INTEGER NOT NULL
        DEFAULT 0,

    siguiente_ejecucion TIMESTAMPTZ NULL,

    ultima_ejecucion TIMESTAMPTZ NULL,

    creado_por UUID NULL,

    fecha_creacion TIMESTAMPTZ NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    fecha_actualizacion TIMESTAMPTZ NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_trabajos_programados_creado_por
        FOREIGN KEY (creado_por)
        REFERENCES app_auth.usuarios (id)
        ON UPDATE CASCADE
        ON DELETE SET NULL,

    CONSTRAINT uq_trabajos_programados_codigo
        UNIQUE (codigo),

    CONSTRAINT ck_trabajos_programados_codigo
        CHECK
        (
            LENGTH(TRIM(codigo)) > 0
        ),

    CONSTRAINT ck_trabajos_programados_nombre
        CHECK
        (
            LENGTH(TRIM(nombre)) > 0
        ),

    CONSTRAINT ck_trabajos_programados_descripcion
        CHECK
        (
            descripcion IS NULL
            OR LENGTH(TRIM(descripcion)) > 0
        ),

    CONSTRAINT ck_trabajos_programados_tipo
        CHECK
        (
            tipo IN
            (
                'CRON',
                'INTERVALO',
                'MANUAL'
            )
        ),

    CONSTRAINT ck_trabajos_programados_programacion
        CHECK
        (
            (
                tipo = 'CRON'
                AND expresion_cron IS NOT NULL
                AND intervalo_segundos IS NULL
            )
            OR
            (
                tipo = 'INTERVALO'
                AND expresion_cron IS NULL
                AND intervalo_segundos IS NOT NULL
            )
            OR
            (
                tipo = 'MANUAL'
                AND expresion_cron IS NULL
                AND intervalo_segundos IS NULL
            )
        ),

    CONSTRAINT ck_trabajos_programados_cron
        CHECK
        (
            expresion_cron IS NULL
            OR LENGTH(TRIM(expresion_cron)) > 0
        ),

    CONSTRAINT ck_trabajos_programados_intervalo
        CHECK
        (
            intervalo_segundos IS NULL
            OR intervalo_segundos > 0
        ),

    CONSTRAINT ck_trabajos_programados_zona_horaria
        CHECK
        (
            LENGTH(TRIM(zona_horaria)) > 0
        ),

    CONSTRAINT ck_trabajos_programados_parametros
        CHECK
        (
            parametros IS NULL
            OR jsonb_typeof(parametros) = 'object'
        ),

    CONSTRAINT ck_trabajos_programados_tiempo_maximo
        CHECK
        (
            tiempo_maximo_segundos IS NULL
            OR tiempo_maximo_segundos > 0
        ),

    CONSTRAINT ck_trabajos_programados_reintentos
        CHECK
        (
            maximo_reintentos BETWEEN 0 AND 100
        ),

    CONSTRAINT ck_trabajos_programados_fechas
        CHECK
        (
            ultima_ejecucion IS NULL
            OR siguiente_ejecucion IS NULL
            OR siguiente_ejecucion >= ultima_ejecucion
        )
);

COMMENT ON TABLE operation.trabajos_programados IS
'Definición de procesos automáticos o manuales ejecutados por los servicios de AlphaInvest AI.';

COMMENT ON COLUMN operation.trabajos_programados.codigo IS
'Código técnico único utilizado para identificar el trabajo.';

COMMENT ON COLUMN operation.trabajos_programados.tipo IS
'Forma de ejecución del trabajo: CRON, INTERVALO o MANUAL.';

COMMENT ON COLUMN operation.trabajos_programados.expresion_cron IS
'Expresión de programación utilizada por trabajos de tipo CRON.';

COMMENT ON COLUMN operation.trabajos_programados.intervalo_segundos IS
'Frecuencia de ejecución para trabajos de tipo INTERVALO.';

COMMENT ON COLUMN operation.trabajos_programados.permite_concurrencia IS
'Indica si pueden existir varias ejecuciones simultáneas del mismo trabajo.';

COMMENT ON COLUMN operation.trabajos_programados.tiempo_maximo_segundos IS
'Tiempo máximo permitido para una ejecución antes de considerarla agotada.';


/*
============================================================
 6. TABLA: operation.ejecuciones_trabajo
============================================================
*/

CREATE TABLE IF NOT EXISTS operation.ejecuciones_trabajo
(
    id UUID
        CONSTRAINT pk_ejecuciones_trabajo
        PRIMARY KEY
        DEFAULT gen_random_uuid(),

    trabajo_id UUID NOT NULL,

    estado VARCHAR(30) NOT NULL
        DEFAULT 'PENDIENTE',

    numero_intento INTEGER NOT NULL
        DEFAULT 1,

    disparador VARCHAR(30) NOT NULL,

    solicitado_por UUID NULL,

    identificador_proceso VARCHAR(150) NULL,

    fecha_programada TIMESTAMPTZ NULL,

    fecha_solicitud TIMESTAMPTZ NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    fecha_inicio TIMESTAMPTZ NULL,

    fecha_fin TIMESTAMPTZ NULL,

    progreso NUMERIC(7,4) NOT NULL
        DEFAULT 0,

    registros_procesados BIGINT NOT NULL
        DEFAULT 0,

    registros_exitosos BIGINT NOT NULL
        DEFAULT 0,

    registros_fallidos BIGINT NOT NULL
        DEFAULT 0,

    resultado JSONB NULL,

    mensaje_error TEXT NULL,

    CONSTRAINT fk_ejecuciones_trabajo_trabajo
        FOREIGN KEY (trabajo_id)
        REFERENCES operation.trabajos_programados (id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,

    CONSTRAINT fk_ejecuciones_trabajo_solicitado_por
        FOREIGN KEY (solicitado_por)
        REFERENCES app_auth.usuarios (id)
        ON UPDATE CASCADE
        ON DELETE SET NULL,

    CONSTRAINT uq_ejecuciones_trabajo_proceso
        UNIQUE (identificador_proceso),

    CONSTRAINT ck_ejecuciones_trabajo_estado
        CHECK
        (
            estado IN
            (
                'PENDIENTE',
                'EJECUTANDO',
                'COMPLETADA',
                'FALLIDA',
                'CANCELADA',
                'OMITIDA'
            )
        ),

    CONSTRAINT ck_ejecuciones_trabajo_intento
        CHECK
        (
            numero_intento > 0
        ),

    CONSTRAINT ck_ejecuciones_trabajo_disparador
        CHECK
        (
            disparador IN
            (
                'PROGRAMADO',
                'MANUAL',
                'REINTENTO',
                'SISTEMA'
            )
        ),

    CONSTRAINT ck_ejecuciones_trabajo_identificador
        CHECK
        (
            identificador_proceso IS NULL
            OR LENGTH(TRIM(identificador_proceso)) > 0
        ),

    CONSTRAINT ck_ejecuciones_trabajo_fechas_inicio
        CHECK
        (
            fecha_inicio IS NULL
            OR fecha_inicio >= fecha_solicitud
        ),

    CONSTRAINT ck_ejecuciones_trabajo_fechas_fin
        CHECK
        (
            fecha_fin IS NULL
            OR
            (
                fecha_inicio IS NOT NULL
                AND fecha_fin >= fecha_inicio
            )
        ),

    CONSTRAINT ck_ejecuciones_trabajo_progreso
        CHECK
        (
            progreso BETWEEN 0 AND 100
        ),

    CONSTRAINT ck_ejecuciones_trabajo_registros
        CHECK
        (
            registros_procesados >= 0
            AND registros_exitosos >= 0
            AND registros_fallidos >= 0
        ),

    CONSTRAINT ck_ejecuciones_trabajo_conteo
        CHECK
        (
            registros_exitosos + registros_fallidos
            <= registros_procesados
        ),

    CONSTRAINT ck_ejecuciones_trabajo_resultado
        CHECK
        (
            resultado IS NULL
            OR jsonb_typeof(resultado) = 'object'
        ),

    CONSTRAINT ck_ejecuciones_trabajo_estado_inicio
        CHECK
        (
            estado = 'PENDIENTE'
            OR estado = 'OMITIDA'
            OR fecha_inicio IS NOT NULL
        ),

    CONSTRAINT ck_ejecuciones_trabajo_estado_fin
        CHECK
        (
            estado NOT IN
            (
                'COMPLETADA',
                'FALLIDA',
                'CANCELADA',
                'OMITIDA'
            )
            OR fecha_fin IS NOT NULL
        ),

    CONSTRAINT ck_ejecuciones_trabajo_completada
        CHECK
        (
            estado <> 'COMPLETADA'
            OR progreso = 100
        ),

    CONSTRAINT ck_ejecuciones_trabajo_fallida
        CHECK
        (
            estado <> 'FALLIDA'
            OR NULLIF(TRIM(mensaje_error), '') IS NOT NULL
        )
);

COMMENT ON TABLE operation.ejecuciones_trabajo IS
'Historial de ejecuciones de los trabajos definidos en el esquema operation.';

COMMENT ON COLUMN operation.ejecuciones_trabajo.numero_intento IS
'Número de intento de ejecución para el mismo procesamiento lógico.';

COMMENT ON COLUMN operation.ejecuciones_trabajo.disparador IS
'Origen que inició la ejecución del trabajo.';

COMMENT ON COLUMN operation.ejecuciones_trabajo.progreso IS
'Porcentaje de avance de la ejecución entre cero y cien.';

COMMENT ON COLUMN operation.ejecuciones_trabajo.resultado IS
'Resumen estructurado del resultado de la ejecución.';


